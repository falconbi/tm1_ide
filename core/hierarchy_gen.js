'use strict'

// Alternate Hierarchy generated from an attribute — the TI that builds and maintains it.
//
// An Alternate Hierarchy is a second named hierarchy in a dimension (e.g. WFP Position "By
// Location"): the same leaves, so the same data, rolled up another way. Built by hand it drifts;
// built from an attribute by a process it stays true. This writes that process: each leaf goes
// under its attribute value, optionally with the levels above taken from another dimension
// (Location → WFP Location: city → country → region). Re-running moves only the leaves whose value
// changed. TM1 v11 notes (docs/models/BUILDING_MODELS.md): the ordinary Dimension functions take
// 'Dim:Hierarchy' as the dimension name; HierarchyCreate makes it.

const q = s => String(s).replace(/'/g, "''")

// 'WFP Position' + 'By Grade' → 'WFP Rebuild By Grade Hierarchy'; a dimension without an
// upper-case prefix keeps its full name ('Region' → 'Region Rebuild By Country Hierarchy').
function processName(dimension, hierarchy) {
    const first = String(dimension).split(' ')[0]
    const prefix = /^[A-Z0-9]{2,}$/.test(first) && first !== dimension ? first : dimension
    return `${prefix} Rebuild ${hierarchy} Hierarchy`
}

/**
 * @param {object} o
 * @param {string} o.dimension       the dimension whose leaves are placed (e.g. 'WFP Position')
 * @param {string} o.hierarchy       the Alternate Hierarchy's name (e.g. 'By Location')
 * @param {string} o.attribute       the attribute holding each leaf's group (e.g. 'Location')
 * @param {string} [o.attributeType] 'String' (default) | 'Numeric'
 * @param {string} [o.levelDimension] optional dimension giving the levels above (e.g. 'WFP Location')
 * @param {string} o.top             the top element (a single root of levelDimension, or 'All <hierarchy>')
 * @param {string} [o.notSet]        where leaves with no / an unknown value go
 * @returns {{ name: string, prolog: string }}
 */
function rebuildProcess(o) {
    const name = processName(o.dimension, o.hierarchy)
    const notSet = o.notSet || `${o.attribute} not set`
    const value = o.attributeType === 'Numeric'
        ? `NUMBERTOSTRING( ATTRN( cDim, vEl, cAttr ) )`
        : `ATTRS( cDim, vEl, cAttr )`
    const lvl = o.levelDimension || ''
    const prolog = `#Region ${name} — the "${o.hierarchy}" Alternate Hierarchy on ${o.dimension}
# Generated by the TM1 IDE (+ Hierarchy → From an attribute). Each leaf of ${o.dimension} sits under
# its ${o.attribute} attribute${lvl ? `; the levels above come from ${lvl}` : ''}. A leaf with no value${lvl ? ` or one ${lvl} doesn't have` : ''}
# goes under '${notSet}'. Only leaves whose value changed are moved. Same leaves as the main
# hierarchy, so the same data. Never edit the hierarchy by hand — run this instead.
#EndRegion
cDim  = '${q(o.dimension)}';
cHier = '${q(o.hierarchy)}';
sDH   = cDim | ':' | cHier;
cAttr = '${q(o.attribute)}';
cLvl  = '${q(lvl)}';
cTop  = '${q(o.top)}';
cNone = '${q(notSet)}';
IF( DimensionExists( sDH ) = 0 ); HierarchyCreate( cDim, cHier ); ENDIF;
IF( DIMIX( sDH, cTop ) = 0 ); DimensionElementInsertDirect( sDH, '', cTop, 'C' ); ENDIF;
${lvl ? `# the levels, mirrored from ${lvl} (its leaves become consolidations here)
nL = 1;
WHILE( nL <= DIMSIZ( cLvl ) );
   vL = DIMNM( cLvl, nL );
   IF( DIMIX( sDH, vL ) = 0 ); DimensionElementInsertDirect( sDH, '', vL, 'C' ); ENDIF;
   nL = nL + 1;
END;
nL = 1;
WHILE( nL <= DIMSIZ( cLvl ) );
   vL = DIMNM( cLvl, nL );
   IF( ELPARN( cLvl, vL ) = 0 & vL @<> cTop );
      IF( ELISPAR( sDH, cTop, vL ) = 0 ); DimensionElementComponentAddDirect( sDH, cTop, vL, 1 ); ENDIF;
   ENDIF;
   nK = 1;
   WHILE( nK <= ELPARN( cLvl, vL ) );
      vParent = ELPAR( cLvl, vL, nK );
      IF( ELISPAR( sDH, vParent, vL ) = 0 ); DimensionElementComponentAddDirect( sDH, vParent, vL, 1 ); ENDIF;
      nK = nK + 1;
   END;
   nL = nL + 1;
END;
` : ''}IF( DIMIX( sDH, cNone ) = 0 ); DimensionElementInsertDirect( sDH, '', cNone, 'C' ); ENDIF;
IF( ELISPAR( sDH, cTop, cNone ) = 0 ); DimensionElementComponentAddDirect( sDH, cTop, cNone, 1 ); ENDIF;
# every leaf under its value — move only the ones that changed
nAll = 0; nMoved = 0;
nE = 1;
WHILE( nE <= DIMSIZ( cDim ) );
   vEl = DIMNM( cDim, nE );
   IF( DTYPE( cDim, vEl ) @= 'N' );
      nAll = nAll + 1;
      vGroup = ${value};
      IF( vGroup @= '' ); vGroup = cNone; ENDIF;
${lvl ? `      IF( DIMIX( cLvl, vGroup ) = 0 ); vGroup = cNone; ENDIF;
` : `      IF( DIMIX( sDH, vGroup ) = 0 );
         DimensionElementInsertDirect( sDH, '', vGroup, 'C' );
         DimensionElementComponentAddDirect( sDH, cTop, vGroup, 1 );
      ENDIF;
`}      vNow = '';
      IF( DIMIX( sDH, vEl ) > 0 ); vNow = ELPAR( sDH, vEl, 1 ); ENDIF;
      IF( vNow @<> vGroup );
         IF( vNow @<> '' ); DimensionElementComponentDeleteDirect( sDH, vNow, vEl ); ENDIF;
         DimensionElementComponentAddDirect( sDH, vGroup, vEl, 1 );
         nMoved = nMoved + 1;
      ENDIF;
   ENDIF;
   nE = nE + 1;
END;
LogOutput( 'INFO', '${q(name)}: ' | NUMBERTOSTRING( nAll ) | ' leaves, ' | NUMBERTOSTRING( nMoved ) | ' placed or moved' );
`
    return { name, prolog }
}

// The code that names this hierarchy — how "built by" is found in existing processes.
function referencesHierarchy(code, dimension, hierarchy) {
    const c = String(code || '')
    return c.includes(`'${q(dimension)}:${q(hierarchy)}'`) ||
        (c.includes(`'${q(dimension)}'`) && c.includes(`'${q(hierarchy)}'`) && /HierarchyCreate|\| ':' \|/i.test(c))
}

module.exports = { processName, rebuildProcess, referencesHierarchy }
